"""Helpers for the output step: a registry of manuscript numbers, LaTeX table writing and figure style.

Every number printed in the manuscript is registered here with the file and the row it comes from. The
registry is written to ``paper/generated/numbers.tex`` (macros read by the manuscript) and to
``results/tables/manuscript_numbers.csv`` (traceability table).
"""
from __future__ import annotations

from pathlib import Path

import matplotlib as mpl
import pandas as pd

# ---------------------------------------------------------------- number registry


class Registry:
    def __init__(self) -> None:
        self.rows: list[dict] = []
        self.keys: set[str] = set()

    def add(self, key: str, value: str, source: str, selector: str = "") -> str:
        if key in self.keys:
            raise KeyError(f"duplicate manuscript number: {key}")
        self.keys.add(key)
        self.rows.append(dict(key=key, value=value, source=source, selector=selector))
        return value

    def write(self, tex_path: Path, csv_path: Path, manuscript: Path | None = None) -> None:
        tex_path.parent.mkdir(parents=True, exist_ok=True)
        lines = ["% Generated by scripts/10_generate_outputs.py - do not edit by hand."]
        lines += [f"\\setval{{{r['key']}}}{{{r['value']}}}" for r in self.rows]
        tex_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        df = pd.DataFrame(self.rows)
        if manuscript is not None and manuscript.exists():
            import re
            used = set(re.findall(r"\\V\{([^}]+)\}", manuscript.read_text(encoding="utf-8")))
            df.insert(2, "used_in_manuscript", df.key.isin(used))
            df = df.sort_values("used_in_manuscript", ascending=False, kind="stable")
        df.to_csv(csv_path, index=False)


def f(x: float, d: int = 3, keep_sign: bool = False) -> str:
    """Fixed decimals with a true minus sign for LaTeX text mode.

    A negative value that rounds to zero is printed without sign, except for interval bounds
    (``keep_sign=True``), where the sign tells whether the interval includes zero.
    """
    s = f"{x:.{d}f}"
    if float(s) == 0 and not keep_sign:
        s = s.lstrip("-")
    return s.replace("-", "$-$")


def fs(x: float, d: int = 3) -> str:
    """Signed version (explicit plus)."""
    s = f(x, d)
    return s if s.startswith("$-$") or float(f"{x:.{d}f}") == 0 else "+" + s


def ci(lo: float, hi: float, d: int = 3) -> str:
    return f"{f(lo, d, True)}, {f(hi, d, True)}"


def pct(x: float, d: int = 1) -> str:
    return f(100 * x, d)


def thousands(n: float) -> str:
    return f"{int(round(n)):,}".replace(",", "{,}")


# ---------------------------------------------------------------- tables

def write_table(path: Path, body: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("% Generated by scripts/10_generate_outputs.py - do not edit by hand.\n" + "\n".join(body) + "\n",
                    encoding="utf-8")


